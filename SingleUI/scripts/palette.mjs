// Single color pipeline: src/design-system/palette.json -> palette.css + public/favicon.svg.
// `node scripts/palette.mjs` writes; `--check` fails when outputs are stale or contrast regresses.
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

const root = new URL('../', import.meta.url);
export const palette = JSON.parse(
  readFileSync(new URL('src/design-system/palette.json', root), 'utf8'),
);

export function color(theme, role) {
  const value = palette.themes[theme]?.[role];
  if (!value) throw new Error(`Unknown ${theme} palette role: ${role}`);
  const resolved = palette.swatches[value] ?? value;
  if (!/^#[0-9a-f]{6}([0-9a-f]{2})?$/i.test(resolved))
    throw new Error(`Invalid ${theme} ${role} color: ${value}`);
  return resolved.toLowerCase();
}

/** Computed-style form (`rgb(r, g, b)`) of an opaque role, for browser assertions. */
export function rgb(theme, role) {
  const [r, g, b] = channels(color(theme, role));
  return `rgb(${r}, ${g}, ${b})`;
}

function channels(hex) {
  return [1, 3, 5].map((index) => parseInt(hex.slice(index, index + 2), 16));
}

function luminance(hex) {
  const [r, g, b] = channels(hex).map((value) => {
    const channel = value / 255;
    return channel <= 0.04045 ? channel / 12.92 : ((channel + 0.055) / 1.055) ** 2.4;
  });
  return 0.2126 * r + 0.7152 * g + 0.0722 * b;
}

export function contrast(a, b) {
  const [light, dark] = [luminance(a), luminance(b)].sort((x, y) => y - x);
  return (light + 0.05) / (dark + 0.05);
}

export function contrastFailures() {
  const failures = [];
  for (const theme of Object.keys(palette.themes))
    for (const [foreground, background, minimum] of palette.contrast) {
      const ratio = contrast(color(theme, foreground), color(theme, background));
      if (ratio < minimum)
        failures.push(`${theme}: ${foreground} on ${background} = ${ratio.toFixed(2)} < ${minimum}`);
    }
  return failures;
}

function declarations(theme, indent) {
  const roles = Object.keys(palette.themes[theme]);
  const value = (role) => color(theme, role);
  return [
    ...roles
      .filter((role) => !['shadow', 'highlight'].includes(role))
      .map((role) => `--color-${role}: ${value(role)};`),
    `--btn-shadow: 0 3px 15px ${value('shadow')};`,
    `--card-highlight: inset 0 1px 0 ${value('highlight')};`,
    `--shadow-card: 0 12px 40px ${value('shadow')};`,
  ]
    .map((line) => indent + line)
    .join('\n');
}

export function css() {
  return `/* Generated by scripts/palette.mjs from palette.json (${palette.name}). Do not edit.
 * Contrast pairs in palette.json are verified at generation; still check rendered
 * default, hover, active, selected, focus-visible, disabled, loading and error states. */
:root {
  color-scheme: light dark;
${declarations('light', '  ')}
}
@media (prefers-color-scheme: dark) {
  :root {
${declarations('dark', '    ')}
  }
}
`;
}

function faviconRoles(theme) {
  return `.tile { fill: url(#${theme}) } .block { fill: ${color(theme, 'action-ink')} } .spark { fill: ${color(theme, 'raised')} }`;
}

/** Warm tile with three stacked, composable blocks. */
export function favicon() {
  const s = palette.swatches;
  return `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 64 64">
  <!-- Generated by scripts/palette.mjs from palette.json. Do not edit. -->
  <defs>
    <linearGradient id="light" x1="0" y1="0" x2="1" y2="1">
      <stop offset="0" stop-color="${s.squashBlossom}"/>
      <stop offset="1" stop-color="${s.icelandPoppy}"/>
    </linearGradient>
    <linearGradient id="dark" x1="0" y1="0" x2="1" y2="1">
      <stop offset="0" stop-color="${s.flatFlesh}"/>
      <stop offset="1" stop-color="${s.carrotOrange}"/>
    </linearGradient>
    <style>
      ${faviconRoles('light')}
      @media (prefers-color-scheme: dark) { ${faviconRoles('dark')} }
    </style>
  </defs>
  <rect class="tile" x="2" y="2" width="60" height="60" rx="16"/>
  <rect class="block" x="14" y="40" width="36" height="10" rx="3.5"/>
  <rect class="block" x="18" y="27" width="28" height="10" rx="3.5"/>
  <rect class="block" x="22" y="14" width="20" height="10" rx="3.5"/>
  <circle class="spark" cx="47" cy="19" r="3.5"/>
</svg>
`;
}

const outputs = [
  ['src/design-system/palette.css', css],
  ['public/favicon.svg', favicon],
];

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const failures = contrastFailures();
  const check = process.argv.includes('--check');
  for (const [path, render] of outputs) {
    const target = new URL(path, root);
    const expected = render();
    if (check) {
      let actual = '';
      try {
        actual = readFileSync(target, 'utf8');
      } catch {}
      if (actual.replace(/\r\n/g, '\n') !== expected) failures.push(`${path} is stale; run npm run palette`);
    } else writeFileSync(target, expected);
  }
  if (failures.length) {
    console.error(failures.join('\n'));
    process.exit(1);
  }
  console.log(check ? 'Palette outputs current; contrast pairs pass.' : 'Wrote palette outputs.');
}
